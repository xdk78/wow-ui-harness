local T = ...

T.case("frames remember what was set; unknown methods are no-ops", function()
	local mock = T.fresh()
	local f = CreateFrame("Frame", "TestFrame", UIParent)
	T.eq(_G.TestFrame, f, "named frames are globals")
	f:SetSize(10, 20)
	T.eq(f:GetWidth(), 10)
	T.eq(f:SomethingTheMockDoesNotKnow(1, 2), nil, "unknown CamelCase method")
	f:Hide()
	T.ok(not f:IsShown())
	T.ok(#mock.frames >= 2)
end)

T.case("anchors: one per point, SetAllPoints, and the client's dependency error", function()
	T.fresh()
	local a = CreateFrame("Frame", nil, UIParent)
	local b = CreateFrame("Frame", nil, UIParent)
	b:SetPoint("TOPLEFT", a, "BOTTOMLEFT", 0, -4)
	b:SetPoint("TOPLEFT", a, "TOPRIGHT", 2, 0)
	T.eq(b:GetNumPoints(), 1, "the same point replaces the old one")
	local t = a:CreateTexture()
	t:SetAllPoints()
	T.eq(t:GetNumPoints(), 2)
	T.ok(not pcall(a.SetPoint, a, "TOP", b, "BOTTOM"), "anchoring to a region that depends on it fails")
end)

T.case("events and timers", function()
	local mock = T.fresh()
	local f = CreateFrame("Frame")
	local got
	f:RegisterEvent("PLAYER_LOGIN")
	f:SetScript("OnEvent", function(_, e)
		got = e
	end)
	mock.FireEvent("PLAYER_LOGIN")
	T.eq(got, "PLAYER_LOGIN")
	local fired = 0
	C_Timer.After(1, function()
		fired = fired + 1
	end)
	mock.Advance(0.5)
	T.eq(fired, 0)
	mock.Advance(0.6)
	T.eq(fired, 1)
end)

T.case("textures and fonts record their state", function()
	T.fresh()
	local f = CreateFrame("Frame")
	local t = f:CreateTexture(nil, "BORDER", nil, 2)
	t:SetAtlas("some-atlas")
	t:SetTexCoord(0, 0.5, 0, 0.5)
	t:SetVertexColor(1, 0, 0)
	T.eq(t:GetAtlas(), "some-atlas")
	T.eq(select(1, t:GetDrawLayer()), "BORDER")
	local fs = f:CreateFontString(nil, "OVERLAY", "GameFontNormal")
	local file, size = fs:GetFont()
	T.eq(file, "Fonts\\FRIZQT__.TTF", "font from the font object")
	T.eq(size, 12)
	fs:SetFont("Fonts\\ARIALN.TTF", 14, "OUTLINE")
	T.eq(select(2, fs:GetFont()), 14)
end)

T.case("templates: a registered template builds its parts", function()
	local mock = T.fresh()
	mock.templates.MyTemplate = function(f)
		f.Text = f:CreateFontString()
	end
	local f = CreateFrame("Button", nil, UIParent, "MyTemplate")
	T.ok(f.Text, "built")
	T.eq(f._template, "MyTemplate")
	T.eq(rawget(CreateFrame("Frame", nil, UIParent, "Unknown"), "Text"), nil, "an unknown template builds nothing")
end)

T.case("synthetic file IDs map back to their paths", function()
	local mock = T.fresh()
	mock.fileResolver = mock.SyntheticFileID
	local id = GetFileIDFromPath("Interface\\Icons\\Foo")
	T.ok(id and id > 2000000000)
	T.eq(GetFileIDFromPath("interface/icons/foo"), id, "case and slashes do not matter")
	T.eq(mock.SyntheticPath(id), "Interface\\Icons\\Foo")
end)
