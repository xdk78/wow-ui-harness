-- Recorded game facts (`wowui.py files --sizes`): texture file sizes, file IDs and atlas sizes without the game.
local T = ...

T.case("a texture with no size takes its file's recorded size (layout only)", function()
	local mock = T.fresh({})
	mock.SetTextureSize("Interface/Buttons/UI-Thing.blp", 64, 32)
	local t = UIParent:CreateTexture()
	t:SetPoint("TOPLEFT")
	t:SetTexture("Interface\\Buttons\\UI-Thing")
	T.eq(t:GetWidth(), 64, "case, slashes and extension do not matter")
	T.eq(t:GetHeight(), 32)
	t:SetSize(10, 0)
	T.eq(t:GetWidth(), 10, "a set size wins")
	T.eq(t:GetHeight(), 32, "a size of 0 is the file's, as in the client")
	t:SetSize(0, 0)
	t:SetPoint("BOTTOMRIGHT", UIParent, "TOPLEFT", 100, -50)
	T.eq(t:GetWidth(), 100, "anchors on both sides win")
	T.eq(t:GetHeight(), 50)
	local unknown = UIParent:CreateTexture()
	unknown:SetPoint("TOPLEFT")
	unknown:SetTexture("Interface\\Buttons\\Unknown")
	T.eq(unknown:GetWidth(), 0, "no recorded size: none")
	local byID = UIParent:CreateTexture()
	byID:SetPoint("TOPLEFT")
	mock.SetTextureSize(130000, 16, 16)
	byID:SetTexture(130000)
	T.eq(byID:GetWidth(), 16, "by file ID")
	byID:SetTexture("130000")
	T.eq(byID:GetWidth(), 16, "a numeric string is the file ID")
	local filled = UIParent:CreateTexture()
	filled:SetTexture("Interface\\Buttons\\UI-Thing")
	filled:SetAllPoints()
	T.eq(filled:GetWidth(), 1920, "SetAllPoints: the anchors' size")
	local atlas = UIParent:CreateTexture()
	atlas:SetPoint("TOPLEFT")
	atlas:SetTexture("Interface\\Buttons\\UI-Thing")
	atlas:SetAtlas("some-atlas")
	T.eq(atlas:GetWidth(), 0, "an atlas replaces the file")
	mock.SetTextureSize("Interface\\Art\\v1.5", 8, 8)
	T.eq(mock.textureSizes[mock.TextureKey("Interface\\Art\\v1.7")], nil, "only image extensions are dropped")
end)

T.case("runner.LoadSizes: file IDs, texture sizes and atlases from a sizes file", function()
	local mock = T.fresh({})
	local Runner = require("wowui.runner")
	mock.atlases["Stub-Atlas"] = { width = 5, height = 6 } -- the addon's own test setup
	local path = os.tmpname()
	local fh = assert(io.open(path, "wb"))
	fh:write([[{"schema": "wowui-sizes/1",
		"files": {"Interface\\Icons\\Foo": {"id": 12345, "size": [64, 64]}, "Interface\\Missing": {"id": 7}},
		"atlases": {"Some-Atlas": [40, 20]}}]])
	fh:close()
	T.ok(Runner.LoadSizes(mock, path))
	os.remove(path)
	T.eq(GetFileIDFromPath("interface/icons/foo"), 12345)
	T.eq(GetFileIDFromPath("Interface\\Missing"), 7, "an ID without a size (not downloaded) still exists")
	T.eq(GetFileIDFromPath("Interface\\Other"), nil)
	local info = C_Texture.GetAtlasInfo("some-atlas")
	T.eq(info.width, 40, "atlases, case-insensitively")
	T.eq(info.height, 20)
	T.eq(C_Texture.GetAtlasInfo("other"), nil, "only the recorded atlases exist")
	T.eq(C_Texture.GetAtlasInfo("stub-atlas").width, 5, "and those the test setup registered")
	T.eq(Runner.LoadSizes(mock, "no/such/file.json"), nil, "a missing file is an error")
	local t = UIParent:CreateTexture()
	t:SetPoint("CENTER")
	t:SetTexture(12345)
	T.eq(t:GetWidth(), 64, "the size by the file's ID")
	local bad = os.tmpname()
	fh = assert(io.open(bad, "wb"))
	fh:write("{}")
	fh:close()
	local ok, err = Runner.LoadSizes(mock, bad)
	os.remove(bad)
	T.eq(ok, nil)
	T.ok(err:find("wowui-sizes/1", 1, true), err)
end)

T.case("the runner records the atlases asked", function()
	local mock = T.fresh()
	mock.atlasQueries = {}
	C_Texture.GetAtlasInfo("Asked-One")
	UIParent:CreateTexture():SetAtlas("Asked-Two")
	T.ok(mock.atlasQueries["Asked-One"] and mock.atlasQueries["Asked-Two"])
end)
