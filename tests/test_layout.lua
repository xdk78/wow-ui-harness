local T = ...

T.case("layout: a centred frame, side anchors, offsets", function()
	T.fresh({ width = 1000, height = 800 })
	local f = CreateFrame("Frame", nil, UIParent)
	f:SetSize(200, 100)
	f:SetPoint("CENTER")
	local l, b, w, h = f:GetRect()
	T.eq(l, 400)
	T.eq(b, 350)
	T.eq(w, 200)
	T.eq(h, 100)
	local c = CreateFrame("Frame", nil, f)
	c:SetPoint("TOPLEFT", 10, -10)
	c:SetPoint("BOTTOMRIGHT", -10, 10)
	T.eq(c:GetWidth(), 180, "two side anchors set the width")
	T.eq(c:GetHeight(), 80)
	T.eq(c:GetLeft(), 410)
	T.eq(c:GetTop(), 440)
end)

T.case("layout: scale multiplies down the chain; offsets scale with the region", function()
	T.fresh({ width = 1000, height = 800 })
	local f = CreateFrame("Frame", nil, UIParent)
	f:SetSize(100, 100)
	f:SetPoint("BOTTOMLEFT", 100, 100)
	f:SetScale(2)
	-- In its own units the frame is 100 wide and sits at 100: on screen 200 wide at 200.
	T.eq(f:GetWidth(), 100)
	T.eq(f:GetLeft(), 100)
	T.eq(f:GetEffectiveScale(), 2)
	local l, _, w = require("wowui.layout").Rect(f)
	T.eq(l, 200)
	T.eq(w, 200)
end)

T.case("layout: no anchors, no rect; anchors to an unresolved region fail too", function()
	T.fresh({})
	local f = CreateFrame("Frame", nil, UIParent)
	f:SetSize(10, 10)
	T.eq(f:GetLeft(), nil)
	local g = CreateFrame("Frame", nil, UIParent)
	g:SetPoint("LEFT", f, "RIGHT")
	T.eq(g:GetLeft(), nil)
end)

T.case("layout: scroll child at the top left, moved by the scroll offset", function()
	T.fresh({ width = 1000, height = 800 })
	local sf = CreateFrame("ScrollFrame", nil, UIParent)
	sf:SetSize(100, 100)
	sf:SetPoint("TOPLEFT", 0, 0)
	local child = CreateFrame("Frame")
	child:SetSize(100, 300)
	sf:SetScrollChild(child)
	T.eq(child:GetTop(), 800)
	sf:SetVerticalScroll(50)
	T.eq(child:GetTop(), 850)
end)

T.case("layout: visibility follows the parent chain; strata and level are inherited", function()
	T.fresh({})
	local f = CreateFrame("Frame", nil, UIParent)
	f:SetFrameStrata("DIALOG")
	local c = CreateFrame("Frame", nil, f)
	T.eq(c:GetFrameStrata(), "DIALOG")
	T.eq(c:GetFrameLevel(), f:GetFrameLevel() + 1)
	f:Hide()
	T.ok(c:IsShown() and not c:IsVisible())
end)

T.case("layout: SettleSizes calls OnSizeChanged for frames whose resolved size changed, cascading", function()
	local M = T.fresh({ width = 1000, height = 800 })
	local Layout = require("wowui.layout")
	local outer = CreateFrame("Frame", nil, UIParent)
	outer:SetSize(400, 100)
	outer:SetPoint("TOPLEFT")
	local half = CreateFrame("Frame", nil, outer)
	half:SetPoint("TOPLEFT")
	half:SetHeight(10)
	local seen = {}
	outer:SetScript("OnSizeChanged", function(_, w)
		seen[#seen + 1] = w
		half:SetWidth(w / 2) -- a handler that sizes a child
	end)
	local inner = {}
	half:SetScript("OnSizeChanged", function(_, w)
		inner[#inner + 1] = w
	end)
	Layout.SettleSizes(M)
	T.eq(seen[1], 400, "the first size")
	T.eq(inner[#inner], 200, "the child's handler saw the size its parent's handler gave it")
	local n = #seen
	Layout.SettleSizes(M)
	T.eq(#seen, n, "nothing changed: no call")
	outer:SetWidth(300)
	Layout.SettleSizes(M)
	T.eq(seen[#seen], 300, "a new width")
	T.eq(inner[#inner], 150)
end)
